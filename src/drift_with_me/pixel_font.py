UNKNOWN_GLYPH: Glyph = ("111", "001", "011", "000", "010")


def glyph_for(char: str) -> Glyph:
    if char == " ":
        return tuple("0" * SPACE_WIDTH for _ in range(FONT_HEIGHT))
    return GLYPHS.get(char.upper(), UNKNOWN_GLYPH)


def pixel_text_size(text: str, scale: int = 2) -> tuple[int, int]:
    if not text:
        return 0, 0
    width = 0
    for index, char in enumerate(text):
        glyph = glyph_for(char)
        width += len(glyph[0]) * scale
        if index != len(text) - 1:
            width += LETTER_SPACING * scale
    return width, FONT_HEIGHT * scale


def draw_pixel_text(pyxel: Any, x: int, y: int, text: str, color: int, scale: int = 2) -> None:
    cursor_x = x
    for char in text:
        glyph = glyph_for(char)
        for row_index, row in enumerate(glyph):
            for col_index, pixel in enumerate(row):
                if pixel == "1":
                    pyxel.rect(
                        cursor_x + col_index * scale,
                        y + row_index * scale,
                        scale,
                        scale,
                        color,
                    )
        cursor_x += (len(glyph[0]) + LETTER_SPACING) * scale
